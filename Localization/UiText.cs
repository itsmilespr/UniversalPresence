    public static UiText For(string? language)
    {
        var code = (language ?? "").Trim().ToLowerInvariant();
        var primary = code.Split('-', '_')[0];
        return primary switch
        {
            "es" => Spanish,
            "pt" => Portuguese,
            "fr" => French,
            "de" => German,
            "it" => Italian,
            "nl" => Dutch,
            "pl" => Polish,
            "ru" => Russian,
            "uk" => Ukrainian,
            "tr" => Turkish,
            "ja" => Japanese,
            "ko" => Korean,
            "id" => Indonesian,
            "sv" => Swedish,
            "cs" => Czech,
            "zh" => SimplifiedChinese,
            "zh-tw" => TraditionalChinese,
            _ => English,
        };
    }

