    public static UiText For(string? language)
    {
        var code = (language ?? "").Trim().ToLowerInvariant();
        var primary = code.Split('-', '_')[0];
        return primary switch
        {
            "es" => Spanish,
            "pt" => Portuguese,
            _ => English,
        };
    }

