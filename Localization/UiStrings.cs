namespace UniversalPresence.Localization;

/// <summary>
/// Textos de las funciones añadidas después de <see cref="UiText"/> (controles de
/// reproducción, estadísticas, inactividad, canal de actualizaciones, portadas propias y
/// asistente inicial).
///
/// Es un diccionario por idioma en lugar de un record posicional: añadir una cadena nueva
/// no obliga a tocar las 18 traducciones de <see cref="UiText"/> y un idioma sin traducir
/// simplemente cae al inglés, nunca deja un hueco vacío en la interfaz.
/// </summary>
public sealed class UiStrings
{
    private readonly Dictionary<string, string> _map;

    private UiStrings(Dictionary<string, string> map) => _map = map;

    public static UiStrings For(string? language)
    {
        var code = (language ?? "").Trim().ToLowerInvariant();
        if (code.StartsWith("zh", StringComparison.Ordinal))
        {
            return new UiStrings(SimplifiedChinese);
        }

        return code.Split('-', '_')[0] switch
        {
            "es" => new UiStrings(Spanish),
            "pt" => new UiStrings(Portuguese),
            "fr" => new UiStrings(French),
            "de" => new UiStrings(German),
            "it" => new UiStrings(Italian),
            _ => new UiStrings(English),
        };
    }

    /// <summary>Cadena traducida; si falta la clave devuelve la inglesa y, en último caso, la clave.</summary>
    public string this[string key]
    {
        get
        {
            if (_map.TryGetValue(key, out var value) && !string.IsNullOrWhiteSpace(value))
            {
                return value;
            }

            return English.TryGetValue(key, out var fallback) ? fallback : key;
        }
    }

    public string T(string key, params object[] args)
    {
        var template = this[key];
        try
        {
            return string.Format(template, args);
        }
        catch (FormatException)
        {
            return template;
        }
    }

    /// <summary>Claves existentes (para el autotest de localización).</summary>
    public static IEnumerable<string> Keys => English.Keys;

    public static bool HasTranslation(string language, string key) =>
        For(language)._map.ContainsKey(key);

